"""
GOHIF Download Executor

Executes download jobs generated by the planner.
"""

from pathlib import Path

import pandas as pd

from src.download_manager.dispatcher import DownloadDispatcher


class DownloadExecutor:
    """
    Execute download jobs from a planner queue.
    """

    def __init__(self):

        self.dispatcher = DownloadDispatcher()

    def execute(self, queue):

        results = []

        if isinstance(queue, (str, Path)):

            queue = pd.read_csv(queue)

        for _, row in queue.iterrows():

            print(f"Downloading: {row['Dataset_Name']}")

            result = self.dispatcher.dispatch(row)

            results.append(result)

        self.dispatcher.close()

        return pd.DataFrame(results)


if __name__ == "__main__":

    print("=" * 70)
    print("GOHIF DOWNLOAD EXECUTOR")
    print("=" * 70)

    executor = DownloadExecutor()

    print()
    print("Executor initialized successfully.")
